#include "oled.hpp"


OLED::OLED(I2C_HandleTypeDef* hi2c, uint8_t address)
{
    _hi2c = hi2c;
    _addr = address << 1;
}

void OLED::sendCommand(uint8_t cmd)
{
    uint8_t data[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(_hi2c, _addr, data, 2, 100);
}

void OLED::sendBuffer()
{
    sendCommand(0x21);
    sendCommand(0);
    sendCommand(OLED_COLS - 1);

    sendCommand(0x22);
    sendCommand(0);
    sendCommand(OLED_PAGES - 1);

    sendCommand(0x40);

    for (int page = 0; page < OLED_PAGES; page++)
    {
        uint8_t chunk[130];
        chunk[0] = 0x40;
        for (int i = 0; i < OLED_COLS; i++)
            chunk[i + 1] = _buf[page * OLED_COLS + i];

        HAL_I2C_Master_Transmit(_hi2c, _addr, chunk, OLED_COLS + 1, 100);
    }
}

void OLED::init()
{
    HAL_Delay(100);

    sendCommand(0xAE);
    sendCommand(0x20);
    sendCommand(0x00);
    sendCommand(0xB0);
    sendCommand(0xC8);
    sendCommand(0x00);
    sendCommand(0x10);
    sendCommand(0x40);
    sendCommand(0x81);
    sendCommand(0xFF);
    sendCommand(0xA1);
    sendCommand(0xA6);
    sendCommand(0xA8);
    sendCommand(0x3F);
    sendCommand(0xA4);
    sendCommand(0xD3);
    sendCommand(0x00);
    sendCommand(0xD5);
    sendCommand(0xF0);
    sendCommand(0xD9);
    sendCommand(0x22);
    sendCommand(0xDA);
    sendCommand(0x12);
    sendCommand(0xDB);
    sendCommand(0x20);
    sendCommand(0x8D);
    sendCommand(0x14);
    sendCommand(0xAF);

    clearBuffer();
    update();
}

void OLED::clearBuffer()
{
    for (int i = 0; i < OLED_BUF_SIZE; i++)
        _buf[i] = 0;
}

void OLED::clear()
{
    clearBuffer();
    update();
}

void OLED::update()
{
    sendBuffer();
}

void OLED::setPixel(uint8_t x, uint8_t y, bool on)
{
    if (x >= OLED_COLS || y >= OLED_HEIGHT)
        return;

    uint8_t page = y / 8;
    uint8_t bit = y % 8;
    uint16_t idx = page * OLED_COLS + x;

    if (on)
        _buf[idx] |= (1 << bit);
    else
        _buf[idx] &= ~(1 << bit);
}

