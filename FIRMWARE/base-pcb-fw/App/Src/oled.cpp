void OLED::drawChar(uint8_t x, uint8_t y, char c)
{
    uint8_t idx = (uint8_t)c - 0x20;
    if (idx > 0x5E)
        return;

    for (uint8_t col = 0; col < 5; col++)
    {
        uint8_t bits = font5x7[idx][col];
        for (uint8_t bit = 0; bit < 7; bit++)
        {
            if (bits & (1 << bit))
                setPixel(x + col, y + bit, true);
        }
    }
}

void OLED::drawString(uint8_t x, uint8_t y, const char* str)
{
    while (*str)
    {
        drawChar(x, y, *str);
        x += 6;
        str++;
    }
}
